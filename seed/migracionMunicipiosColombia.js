const run = async () => {
    await db.authenticate();

    // Duplicados dentro de la propia lista (si los hubiera) — se quedan con el primero y
    // se avisa cuáles se descartaron, antes de tocar la base.
    const vistos = new Map();
    const unicos = [];
    for (const m of municipios) {
        if (vistos.has(m.id)) {
            console.log(`· Duplicado en la lista, se ignora: ${m.id} (${m.nombre}) — ya estaba como ${vistos.get(m.id)}`);
            continue;
        }
        vistos.set(m.id, m.nombre);
        unicos.push(m);
    }

    const [{ n: antes }] = await db.query('SELECT COUNT(*) n FROM MUNICIPIOS', { type: db.QueryTypes.SELECT });

    // ignoreDuplicates → INSERT IGNORE: una fila cuyo `id` ya exista en MUNICIPIOS se
    // salta sola, sin lanzar error y sin pisar lo que ya había.
    await Municipios.bulkCreate(unicos, { ignoreDuplicates: true });

    const [{ n: despues }] = await db.query('SELECT COUNT(*) n FROM MUNICIPIOS', { type: db.QueryTypes.SELECT });

    console.log(`\nEnviados: ${municipios.length} · únicos en la lista: ${unicos.length}`);
    console.log(`MUNICIPIOS antes: ${antes} · después: ${despues} · nuevos insertados: ${despues - antes}`);
    console.log(`Ya existían (ignorados por INSERT IGNORE): ${unicos.length - (despues - antes)}`);

    process.exit(0);
};

